def get_weights(list_level):
    """
    Calculate normalized linear weights for selected order book levels.
    Higher weights are assigned to levels closer to the best bid/ask.
    
    Parameters
    ----------
    list_level : list[int]
        Order book levels to include (0 to 9).

    Returns
    -------
    dict
        Dictionary mapping each level to its normalized weight.
    """

    # Format levels as two-digit strings
    list_str_level = [f"{level:02d}" for level in list_level]

    # Assign linearly decreasing weights based on order book depth
    list_weights = [10 - x for x in list_level]

    # Normalize weights so they sum to 1
    total_weight = sum(list_weights)
    list_weights = [x / total_weight for x in list_weights]

    # Map each order book level to its corresponding weight
    dict_weights = dict(zip(list_str_level, list_weights))

    return dict_weights

def get_weighted_bid_ask(df_full, list_level):
    """
    Calculate the weighted average bid and ask liquidity for selected
    order book levels.

    Parameters
    ----------
    df_full : pd.DataFrame
        DataFrame containing MBP-10 order book data.
    list_level : list[int]
        Order book levels to include (0 to 9).

    Returns
    -------
    pd.DataFrame
        DataFrame containing timestamps and weighted bid/ask liquidity.
    """

    # Validate that levels are within the available MBP-10 range
    if not list_level or any(level < 0 or level > 9 for level in list_level):
        raise ValueError("All levels must be between 0 and 9, and the list cannot be empty.")

    # Ensure that no levels are repeated
    if len(list_level) != len(set(list_level)):
        raise ValueError("Levels must be unique.")

    # Calculate normalized weights for the selected levels
    dict_level = get_weights(list_level)

    # Select the corresponding bid and ask size columns
    bid_cols = ["bid_sz_" + liq_level for liq_level in dict_level]
    ask_cols = ["ask_sz_" + liq_level for liq_level in dict_level]

    # Convert sizes to float to avoid unsigned integer underflow
    df_bid = df_full[bid_cols].copy().astype(float)
    df_ask = df_full[ask_cols].copy().astype(float)

    # Calculate weighted average liquidity using the dot product
    avg_bid = np.dot(
        df_bid[bid_cols],
        list(dict_level.values())
    )

    avg_ask = np.dot(
        df_ask[ask_cols],
        list(dict_level.values())
    )

    # Store the weighted liquidity for each order book event
    df_bidask = df_full[["ts_event"]].copy()
    df_bidask["bid"] = avg_bid
    df_bidask["ask"] = avg_ask

    return df_bidask


def get_OBI(info_df, list_levels):
    """
    Calculate the Order Book Imbalance (OBI) using selected order book levels.

    Parameters
    ----------
    info_df : pd.DataFrame
        DataFrame containing MBP-10 order book data.
    list_levels : list[int]
        Order book levels to include (0 to 9).

    Returns
    -------
    pd.DataFrame
        DataFrame containing timestamps, weighted bid/ask liquidity,
        and the calculated OBI.
    """

    # Calculate weighted bid and ask liquidity
    df_bid_ask = get_weighted_bid_ask(info_df, list_levels)

    # Calculate OBI, avoiding division by zero
    denominator = df_bid_ask["bid"] + df_bid_ask["ask"]

    df_bid_ask["OBI"] = np.divide(
        df_bid_ask["bid"] - df_bid_ask["ask"],
        denominator,
        out=np.zeros(len(df_bid_ask)),
        where=denominator != 0
    )

    return df_bid_ask


